import { createHmac } from "node:crypto";
const [, , method = "GET", body = ""] = process.argv;
const p = { shop: "urban-deco-dev.myshopify.com", logged_in_customer_id: "", path_prefix: "/apps/cfs", timestamp: String(Math.floor(Date.now() / 1000)) };
if (method === "GET") p.t = "7958a950fefe06664d05bd6dd9eaa1064c5655fa6bd1d616";
const msg = Object.keys(p).sort().map((k) => `${k}=${p[k]}`).join("");
p.signature = createHmac("sha256", process.env.SHOPIFY_API_SECRET).update(msg).digest("hex");
const url = `https://cfs-order-status-panel.onrender.com/proxy/delivery-confirm${method === "POST" ? "/" : ""}?${new URLSearchParams(p)}`;
const res = await fetch(url, { method, headers: method === "POST" ? { "Content-Type": "application/x-www-form-urlencoded" } : {}, body: method === "POST" ? body : undefined });
const text = await res.text();
console.log(res.status, res.headers.get("content-type"));
